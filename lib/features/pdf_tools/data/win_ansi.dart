/// Windows-1252 code of the characters that sit outside Latin-1 in Unicode.
const Map<int, int> _extended = {
  0x20AC: 0x80, // €
  0x201A: 0x82,
  0x0192: 0x83,
  0x201E: 0x84,
  0x2026: 0x85, // …
  0x2020: 0x86,
  0x2021: 0x87,
  0x02C6: 0x88,
  0x2030: 0x89,
  0x0160: 0x8A,
  0x2039: 0x8B,
  0x0152: 0x8C, // Œ
  0x017D: 0x8E,
  0x2018: 0x91,
  0x2019: 0x92, // ’
  0x201C: 0x93,
  0x201D: 0x94,
  0x2022: 0x95,
  0x2013: 0x96, // –
  0x2014: 0x97, // —
  0x02DC: 0x98,
  0x2122: 0x99,
  0x0161: 0x9A,
  0x203A: 0x9B,
  0x0153: 0x9C, // œ
  0x017E: 0x9E,
  0x0178: 0x9F,
  // Typographic spaces have no glyph of their own in the base fonts.
  0x0009: 0x20,
  0x2007: 0x20,
  0x2009: 0x20,
  0x202F: 0xA0,
};

/// Converts [text] to Windows-1252, the encoding of the PDF base fonts: the
/// result has one code unit per byte. Returns null when a character cannot
/// be represented, so the caller can refuse the text instead of printing a
/// wrong glyph.
String? encodeWinAnsi(String text) {
  final codes = <int>[];
  for (final rune in text.runes) {
    final direct =
        (rune >= 0x20 && rune <= 0x7E) || (rune >= 0xA0 && rune <= 0xFF);
    final code = direct ? rune : _extended[rune];
    if (code == null) return null;
    codes.add(code);
  }
  return String.fromCharCodes(codes);
}
